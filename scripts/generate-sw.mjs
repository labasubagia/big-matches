// Post-build: write a service worker into dist/client/sw.js.
// Route HTML is precached eagerly (small, fast paint); all other assets are
// cached on demand on first use, so a fresh visit isn't slowed by a fetch
// storm while offline still works after a normal visit.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const CLIENT_DIR = "dist/client";
const BASE = "/big-matches/";

function walk(dir) {
	const out = [];
	for (const name of readdirSync(dir)) {
		const p = join(dir, name);
		if (statSync(p).isDirectory()) out.push(...walk(p));
		else out.push(p);
	}
	return out;
}

const files = walk(CLIENT_DIR);
const urls = files.map((f) => `${BASE}${f.slice(CLIENT_DIR.length + 1)}`);

// Navigation shell: every route index.html (and the root index).
const precache = urls.filter(
	(u) => u.endsWith("/index.html") || u === `${BASE}index.html`,
);

const version = createHash("sha1")
	.update(precache.join("\n"))
	.digest("hex")
	.slice(0, 12);
const cacheName = `big-matches-${version}`;

const sw = `/* Generated by scripts/generate-sw.mjs — do not edit. */
const CACHE = ${JSON.stringify(cacheName)};
const PRECACHE = ${JSON.stringify(precache)};
const NAV_FALLBACK = ${JSON.stringify(`${BASE}index.html`)};

self.addEventListener("install", (event) => {
	event.waitUntil(
		caches
			.open(CACHE)
			.then((cache) =>
				Promise.allSettled(
					PRECACHE.map((url) => cache.add(url).catch(() => {})),
				),
			)
			.then(() => self.skipWaiting()),
	);
});

self.addEventListener("activate", (event) => {
	event.waitUntil(
		caches
			.keys()
			.then((keys) =>
				Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))),
			)
			.then(() => self.clients.claim()),
	);
});

self.addEventListener("fetch", (event) => {
	const { request } = event;
	if (request.method !== "GET") return;
	const url = new URL(request.url);
	if (url.origin !== self.location.origin) return;

	const put = (res) => {
		if (res.ok) {
			const copy = res.clone();
			caches.open(CACHE).then((c) => c.put(request, copy));
		}
		return res;
	};

	// Navigation: network-first, fall back to the cached route (or root).
	if (request.mode === "navigate") {
		event.respondWith(
			fetch(request)
				.then(put)
				.catch(async () => {
					const cache = await caches.open(CACHE);
					return (
						(await cache.match(request)) ||
						(await cache.match(url.href.replace(/\\/?$/, "") + "/index.html")) ||
						(await cache.match(NAV_FALLBACK))
					);
				}),
		);
		return;
	}

	// Static assets: cache-first (content-addressed by build hash).
	event.respondWith(
		caches.match(request).then((cached) => cached || fetch(request).then(put)),
	);
});
`;

writeFileSync(join(CLIENT_DIR, "sw.js"), sw);
console.log(`sw.js written (${precache.length} html urls, cache ${cacheName})`);

// Inject <link rel="preload"> for the entry stylesheet + main script into each
// prerendered route HTML so they start fetching before later chunks are seen.
function injectPreload(html) {
	const css = html.match(/<link[^>]*rel="stylesheet"[^>]*>/);
	const entry = html.match(/<script[^>]*type="module"[^>]*src="([^"]+)"[^>]*>/);
	if (!css && !entry) return html;
	const links = [];
	if (css) {
		const href = css[0].match(/href="([^"]+)"/)?.[1];
		if (href) links.push(`<link rel="preload" as="style" href="${href}">`);
	}
	if (entry) {
		links.push(`<link rel="preload" as="script" href="${entry[1]}">`);
	}
	if (links.length === 0) return html;
	return html.replace("<head>", `<head>\n${links.join("\n")}`);
}

for (const p of files.filter((f) => f.endsWith("index.html"))) {
	const html = readFileSync(p, "utf8");
	const out = injectPreload(html);
	if (out !== html) writeFileSync(p, out);
}
